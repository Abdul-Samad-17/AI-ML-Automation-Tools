SYSTEM_PROMPT = """You are a helpful assistant for Calder, a business productivity platform.
Answer questions accurately and concisely based ONLY on the provided context.
If the context does not contain enough information to answer the question, say so clearly and politely.
Do not make up information. Keep answers focused and professional.
Format your response in plain text without markdown unless specifically helpful."""

FALLBACK_RESPONSE = (
    "I'm sorry, I couldn't find relevant information to answer your question. "
    "Please contact our support team at support@calder.ai or call +92 349 5904995 for assistance."
)


class RAGChatbot:
    SIMILARITY_THRESHOLD = 0.02
    TOP_K = 3

    def __init__(self, api_key: str | None = None):
        self.api_key = api_key or os.environ.get("ANTHROPIC_API_KEY", "")
        self.vector_store = VectorStore()
        self.conversation_history: list[dict] = []
        self._build_knowledge_base()

    def _build_knowledge_base(self):
        """Index the knowledge base into the vector store."""
        self.vector_store.add_documents(KNOWLEDGE_BASE)
        print(f"✓ Knowledge base indexed | {len(KNOWLEDGE_BASE)} documents")

    def add_documents(self, documents: list[str]):
        """Add additional documents to the knowledge base at runtime."""
        all_docs = KNOWLEDGE_BASE + documents
        self.vector_store.add_documents(all_docs)

    def _retrieve_context(self, query: str) -> list[dict]:
        """Retrieve relevant documents for a query."""
        results = self.vector_store.search(query, top_k=self.TOP_K)
        return [r for r in results if r["score"] >= self.SIMILARITY_THRESHOLD]

    def _build_prompt(self, query: str, context_docs: list[dict]) -> str:
        """Build the prompt with retrieved context."""
        context_text = "\n\n".join(
            f"[Context {i+1}]: {doc['document']}"
            for i, doc in enumerate(context_docs)
        )
        return (
            f"Context:\n{context_text}\n\n"
            f"User Question: {query}\n\n"
            f"Please answer based on the context above."
        )

    def chat(self, query: str) -> dict:
        """
        Process a user query through the RAG pipeline.

        Returns:
            dict with: answer, retrieved_docs, used_llm, query
        """
        if not query.strip():
            return {"answer": "Please enter a valid question.", "retrieved_docs": [], "used_llm": False}

        # Step 1: Retrieve
        retrieved = self._retrieve_context(query)

        # Step 2: Fallback if no relevant context
        if not retrieved:
            return {
                "answer": FALLBACK_RESPONSE,
                "retrieved_docs": [],
                "used_llm": False,
                "query": query,
            }

        # Step 3: Generate with LLM if API key available
        if self.api_key:
            try:
                prompt = self._build_prompt(query, retrieved)
                answer = call_claude_api(SYSTEM_PROMPT, prompt, self.api_key)
                used_llm = True
            except Exception as e:
                # Graceful fallback: return best retrieved document
                answer = f"[LLM unavailable: {e}]\n\n{retrieved[0]['document']}"
                used_llm = False
        else:
            # No API key: return best retrieved document as answer
            answer = retrieved[0]["document"]
            used_llm = False

        self.conversation_history.append({"role": "user", "content": query})
        self.conversation_history.append({"role": "assistant", "content": answer})

        return {
            "answer": answer,
            "retrieved_docs": retrieved,
            "used_llm": used_llm,
            "query": query,
        }

    def run_cli(self):
        """Interactive CLI for the RAG chatbot."""
        print("=" * 60)
        print("  Calder RAG Chatbot  |  Type 'exit' to quit")
        if not self.api_key:
            print("  [Note: No API key set — using retrieval-only mode]")
            print("  Set ANTHROPIC_API_KEY env var to enable LLM generation")
        print("=" * 60)

        while True:
            try:
                query = input("\nYou: ").strip()
            except (EOFError, KeyboardInterrupt):
                break

            if not query:
                continue
            if query.lower() in {"exit", "quit", "bye"}:
                print("Bot: Goodbye!")
                break

            result = self.chat(query)
            print(f"\nBot: {result['answer']}")

            if result["retrieved_docs"]:
                print(f"\n[Retrieved {len(result['retrieved_docs'])} docs | "
                      f"LLM: {'yes' if result['used_llm'] else 'no (retrieval-only)'}]")

        print("\nSession ended.")


