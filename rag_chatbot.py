# Text Preprocessing
# ─────────────────────────────────────────────

STOP_WORDS = {
    "a", "an", "the", "is", "it", "in", "on", "at", "to", "do", "i",
    "my", "me", "we", "our", "you", "your", "can", "will", "be", "am",
    "are", "was", "were", "has", "have", "had", "this", "that", "of",
    "for", "with", "about", "from", "or", "and", "not", "but", "so",
    "if", "as", "by", "its", "been", "into", "each", "also", "any",
    "all", "via", "per",
}


def preprocess(text: str) -> list[str]:
    text = text.lower()
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    return [t for t in text.split() if t not in STOP_WORDS and len(t) > 1]


# ─────────────────────────────────────────────
# In-Memory Vector Store (FAISS-compatible interface)
# ─────────────────────────────────────────────

class VectorStore:
    """Simple in-memory TF-IDF vector store with cosine similarity search."""

    def __init__(self):
        self.documents: list[str] = []
        self.vectors: list[dict[str, float]] = []
        self.idf: dict[str, float] = {}

    def _build_idf(self):
        N = len(self.documents)
        tokenized = [preprocess(d) for d in self.documents]
        vocab = {w for toks in tokenized for w in toks}
        for word in vocab:
            df = sum(1 for toks in tokenized if word in toks)
            self.idf[word] = math.log((N + 1) / (df + 1)) + 1

    def _tfidf_vector(self, tokens: list[str]) -> dict[str, float]:
        tf = Counter(tokens)
        total = len(tokens) if tokens else 1
        return {w: (c / total) * self.idf.get(w, 0) for w, c in tf.items()}

    def add_documents(self, documents: list[str]):
        """Embed and store documents."""
        self.documents = list(documents)
        self._build_idf()
        tokenized = [preprocess(d) for d in self.documents]
        self.vectors = [self._tfidf_vector(toks) for toks in tokenized]

    def search(self, query: str, top_k: int = 3) -> list[dict]:
        """Return top-K most relevant documents with scores."""
        q_tokens = preprocess(query)
        q_vec = self._tfidf_vector(q_tokens)

        scores = []
        for i, vec in enumerate(self.vectors):
            dot = sum(q_vec.get(k, 0) * vec.get(k, 0) for k in q_vec)
            na = math.sqrt(sum(v**2 for v in q_vec.values()))
            nb = math.sqrt(sum(v**2 for v in vec.values()))
            sim = dot / (na * nb) if na and nb else 0.0
            scores.append((i, sim))

        scores.sort(key=lambda x: x[1], reverse=True)
        return [
            {"document": self.documents[i], "score": round(s, 4)}
            for i, s in scores[:top_k]
            if s > 0
        ]


# ─────────────────────────────────────────────
# LLM Response Generator (Claude API)
# ─────────────────────────────────────────────

CLAUDE_API_URL = "https://api.anthropic.com/v1/messages"
CLAUDE_MODEL = "claude-sonnet-4-20250514"


def call_claude_api(system_prompt: str, user_message: str, api_key: str) -> str:
    """Call the Claude API and return the text response."""
    payload = {
        "model": CLAUDE_MODEL,
        "max_tokens": 512,
        "system": system_prompt,
        "messages": [{"role": "user", "content": user_message}],
    }

    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        CLAUDE_API_URL,
        data=data,
        headers={
            "Content-Type": "application/json",
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            body = json.loads(resp.read().decode("utf-8"))
            return body["content"][0]["text"]
    except urllib.error.HTTPError as e:
        error_body = e.read().decode("utf-8")
        raise RuntimeError(f"Claude API error {e.code}: {error_body}")


